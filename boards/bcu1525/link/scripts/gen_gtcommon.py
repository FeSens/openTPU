#!/usr/bin/env python3
"""The link test's GTYE4_COMMON per line rate (rtl/gen/lt_gtcommon_r<rate>.v), from the Aurora
64B/66B core's example design with the shared logic outside the core (SupportLevel 0): its
<ip>_gt_gtye4_common_wrapper.v (the attributes) and <ip>_gt_common_wrapper.v (the ports).

The Aurora IP offers only MGTREFCLK0 at 25.78125 Gb/s, and the BCU1525's 161.1328125 MHz
oscillators (SI5335 U9 / U12) sit on each quad's MGTREFCLK1. The PLL the core uses (QPLL0 at
25.78125, QPLL1 at 10.3125) takes its reference from GTREFCLK1<pll> here (QPLL<pll>REFCLKSEL
3'b010), everything else as the IP set it. The module's NB picks a neighbour quad's MGTREFCLK1
instead: 1 the south-bound clock from the quad above (GTSOUTHREFCLK1<pll>, 3'b110), 2 the
north-bound one from the quad below (GTNORTHREFCLK1<pll>, 3'b100); v6's quad 230 takes quad
231's (U9) so that no image drives an SI5335 pin. Usage:
  gen_gtcommon.py RATE <ip>_gt_common_wrapper.v <ip>_gt_gtye4_common_wrapper.v OUT [MODULE]

The two wrappers are what Vivado writes for the core's example design (open_example_project on an
aurora_64b66b IP at the rate, SupportLevel 0); they are AMD's and are not in this repository. The
output is this project's module around the GTYE4_COMMON primitive: of the IP it keeps the
attribute values and tie-offs the core computes for the line rate and reference (settings, as a
transceiver wizard reports them). MODULE names it (the two-card link's is otpu_link_gtcommon_bcu,
boards/bcu1525/link/otpu_link_gtcommon_bcu.v; default lt_gtcommon_r<rate>)."""
import re
import sys
from pathlib import Path


def attributes(src: str) -> list[tuple[str, str]]:
    m = re.search(r"gtwizard_ultrascale_v\w*_gtye4_common #\(", src)
    body = src[m.end():src.index(") common_inst", m.end())]
    out = []
    for name, val in re.findall(r"\.GTYE4_COMMON_(\w+)\s*\(([^()]*)\)", body):
        if not (name.endswith("_TIE_EN") or name.endswith("_VAL")):
            out.append((name, val.strip()))
    return out


def ports(src: str) -> tuple[dict, dict, int]:
    """The primitive's inputs as the wrapper ties them, its outputs to this module's, the PLL."""
    assigns = dict(re.findall(r"assign\s+(\w+)\s*=\s*([^;]+);", src))
    pll = 0 if "qpll0_refclk" in src else 1
    mine = {f"qpll{pll}_refclk": "refclk", f"qpll{pll}_reset": "reset",
            f"qpll{pll}_lock_detclk": "lockdetclk"}
    outs = {f"QPLL{pll}LOCK": "lock", f"QPLL{pll}OUTCLK": "outclk",
            f"QPLL{pll}OUTREFCLK": "outrefclk", f"QPLL{pll}REFCLKLOST": "refclklost"}
    i = src.index("_gt_gtye4_common_wrapper_i")
    ins = {}
    for name, expr in re.findall(r"\.GTYE4_COMMON_(\w+)\s*\(([^()]*)\)", src[i:]):
        expr = expr.strip()
        if not expr or name in outs:
            continue
        if expr.startswith("GTYE4_COMMON_"):
            expr = assigns[expr].strip()
        ins[name] = mine.get(expr, expr)
    return ins, outs, pll


def main() -> None:
    rate, cw, gw, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4])
    module = sys.argv[5] if len(sys.argv) > 5 else f"lt_gtcommon_r{rate.replace('.', '')[:2]}"
    attrs = attributes(gw.read_text())
    assert len(attrs) == 89, len(attrs)
    ins, outs, pll = ports(cw.read_text())
    assert ins[f"GTREFCLK0{pll}"] == "refclk" and ins[f"QPLL{pll}REFCLKSEL"] == "3'b001", ins
    for n in (f"GTREFCLK1{pll}", f"GTSOUTHREFCLK1{pll}", f"GTNORTHREFCLK1{pll}"):
        assert ins[n] == "1'b0", (n, ins[n])
    ins[f"GTREFCLK0{pll}"] = "1'b0"
    ins[f"GTREFCLK1{pll}"] = "NB == 0 ? refclk : 1'b0"
    ins[f"GTSOUTHREFCLK1{pll}"] = "NB == 1 ? refclk : 1'b0"
    ins[f"GTNORTHREFCLK1{pll}"] = "NB == 2 ? refclk : 1'b0"
    ins[f"QPLL{pll}REFCLKSEL"] = "NB == 1 ? 3'b110 : NB == 2 ? 3'b100 : 3'b010"
    w = max(len(n) for n, _ in attrs + list(ins.items()))
    lines = [
        f"// Generated by boards/bcu1525/link/scripts/gen_gtcommon.py from {gw.name} and {cw.name}",
        "// (Vivado's Aurora 64B/66B 13.0 example design, SupportLevel 0, 161.1328125 MHz) -- do not edit.",
        f"// QPLL{pll} for {rate} Gb/s, its reference from the quad's MGTREFCLK1 (GTREFCLK1{pll},",
        f"// QPLL{pll}REFCLKSEL 3'b010) or with NB a neighbour's: 1 from the quad above (GTSOUTHREFCLK1{pll},",
        f"// 3'b110), 2 from the quad below (GTNORTHREFCLK1{pll}, 3'b100); the IP's other attributes and",
        "// ties as generated.",
        "`timescale 1ps/1ps",
        f"module {module} #(parameter NB = 0) (",
        "  input  wire refclk,",
        "  input  wire lockdetclk,",
        "  input  wire reset,",
        "  output wire lock,",
        "  output wire outclk,",
        "  output wire outrefclk,",
        "  output wire refclklost",
        ");",
        "  GTYE4_COMMON #(",
    ]
    lines += [f"    .{n:<{w}} ({v})," for n, v in attrs]
    lines[-1] = lines[-1].rstrip(",")
    lines.append("  ) u_common (")
    conns = [f"    .{n:<{w}} ({v})," for n, v in sorted(ins.items())]
    conns += [f"    .{n:<{w}} ({v})," for n, v in sorted(outs.items())]
    conns[-1] = conns[-1].rstrip(",")
    lines += conns
    lines += ["  );", "endmodule", ""]
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
