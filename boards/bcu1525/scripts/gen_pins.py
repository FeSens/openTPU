#!/usr/bin/env python3
"""The BCU1525's pin constraints (boards/bcu1525/constraints/*.xdc) from AMD's VCU1525 board files.

The BCU1525 (Bitmain) and XCU1525 (SQRL) are builds of Xilinx's VCU1525 (docs/bcu1525.md): the pins
are the VCU1525's. Source: XilinxBoardStore branch 2024.1, boards/Xilinx/vcu1525/1.3
(part0_pins.xml, Apache License 2.0, Copyright 2023 Advanced Micro Devices, Inc.), checked against
the device package file xcvu9pfsgd2104pkg.txt (AMD's UltraScale+ package files): every pin is in
the package, each channel's pins sit in that channel's three banks, and each DQS pair strobes the
nibble of four DQ pins it shares a byte-group nibble with (MIG's x4 order: dqs[k] <-> dq[4k+3:4k]),
which is the order LiteDRAM's x4 PHY takes (byte i on dqs[2i], dqs[2i+1]).

    python3 boards/bcu1525/scripts/gen_pins.py [--pins part0_pins.xml] [--pkg xcvu9pfsgd2104pkg.txt]

Without the paths it downloads both. Writes constraints/ddr4_c{0..3}.pins.xdc (the x4 RDIMMs),
constraints/ddr4_c{0..3}.udimm.pins.xdc (x8 UDIMMs without ECC: create_project.tcl's DIMM udimm)
and constraints/bcu1525_pins.xdc (clocks, PCIe, LEDs, UART, I2C) and prints the checks.

An x8 UDIMM on the same pins: the board file's bytes are not the DIMM's in order, and one of
them (CB_BYTE) is the DIMM's check-bit byte CB0..7, which a UDIMM without ECC does not have; the
board file's byte 8 (dq[71:64]) is a data byte. The UDIMM's byte i is the board file's byte i, or
byte 8 in place of CB_BYTE. Byte b's strobe is the board's dqs[2b] (the DIMM's DQS_i), its data
mask DM_n dqs_t[2b+1] (the DIMM's DQS(9+i)_t, which an x8 DIMM's DM_n / DBI_n takes; its
DQS(9+i)_c is not connected).

Top-level port names (LiteX's DDR4 pad names, the ports of rtl/boards/bcu1525's top):
  ddr4_c<n>_a[13:0]   adr0..13         ddr4_c<n>_we_n / cas_n / ras_n   adr14 / adr15 / adr16
  ddr4_c<n>_act_n, ba[1:0], bg[1:0], cke, odt, cs_n, reset_n, par
  ddr4_c<n>_clk_p / clk_n             ck_t0 / ck_c0
  ddr4_c<n>_dq[71:0], dqs_p[17:0], dqs_n[17:0]     (UDIMM: dq[63:0], dqs_p[7:0], dqs_n[7:0], dm[7:0])
  ddr4_c<n>_cs_hi[2:0]  cs1_n..cs3_n, driven high (one rank: the others deselected)
  ddr4_c<n>_cke1, ddr4_c<n>_odt1     the second CKE / ODT, driven low
"""
import argparse
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "constraints"
PINS_URL = ("https://raw.githubusercontent.com/Xilinx/XilinxBoardStore/2024.1/boards/Xilinx/vcu1525/"
            "1.3/part0_pins.xml")
PKG_URL = ("https://www.xilinx.com/content/dam/xilinx/support/packagefiles/usapackages/"
           "xcvu9pfsgd2104pkg.txt")
BANKS = {0: (40, 41, 42), 1: (65, 66, 67), 2: (46, 47, 48), 3: (70, 71, 72)}
SLR = {0: 0, 1: 1, 2: 1, 3: 2}
# Each channel's board-file byte that is the DIMM's check-bit byte (CB0..7). An RDIMM with ECC uses
# all nine bytes, so the board file's order need not be the DIMM's; a UDIMM without ECC has no DRAM
# there. On the card (2026-10-21, 10-26) that byte never drove DQ in write leveling (0xff at every
# delay) with its strobe on either nibble's pair; LiteX's sqrl_xcu1525 platform (64-bit) leaves
# these four bytes out and takes the board file's byte 8 in their place, with dqs[16] its strobe.
CB_BYTE = {0: 7, 1: 7, 2: 3, 3: 2}
HEADER = """# Generated by boards/bcu1525/scripts/gen_pins.py -- do not edit.
# Pins: AMD XilinxBoardStore 2024.1, boards/Xilinx/vcu1525/1.3/part0_pins.xml
# (Copyright 2023 Advanced Micro Devices, Inc., Apache License 2.0); the BCU1525 is a VCU1525 build.
# I/O standards: the VCU1525 board file's and the DDR4 MIG's for UltraScale+ (POD12_DCI data,
# SSTL12_DCI address / command, DIFF_SSTL12_DCI clock, LVCMOS12 reset), drive settings as LiteX's
# sqrl_xcu1525 platform (BSD-2-Clause).
"""


def fetch(path, url):
    if path:
        return Path(path).read_text()
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=60).read().decode()


def board_pins(text):
    """name -> (loc, attributes)"""
    out = {}
    for m in re.finditer(r'<pin\s+index="\d+"\s+name\s*="([^"]+)"([^/]*)/>', text):
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', m.group(2)))
        out[m.group(1)] = attrs
    return out


def package(text):
    """pin -> (name, byte group, bank, io type, slr)"""
    pk = {}
    for line in text.splitlines():
        f = line.split()
        if line.startswith("--") or len(f) != 6 or f[0] == "Pin":
            continue
        pk[f[0]] = tuple(f[1:])
    return pk


def ddr4(ch, bp, pk, problems, udimm=False):
    p = f"c{ch}_ddr4_"
    loc = lambda n: bp[p + n]["loc"]
    ports = []                                   # (port, loc, iostandard, extra properties)
    cmd = "SSTL12_DCI"
    for i in range(14):
        ports.append((f"a[{i}]", loc(f"adr{i}"), cmd, []))
    for name, adr in (("we_n", 14), ("cas_n", 15), ("ras_n", 16)):
        ports.append((name, loc(f"adr{adr}"), cmd, []))
    for i in range(2):
        ports.append((f"ba[{i}]", loc(f"ba{i}"), cmd, []))
        ports.append((f"bg[{i}]", loc(f"bg{i}"), cmd, []))
    ports += [("act_n", loc("act_n"), cmd, []), ("cke", loc("cke0"), cmd, []),
              ("odt", loc("odt0"), cmd, []), ("cs_n", loc("cs0_n"), cmd, []),
              ("par", loc("parity"), cmd, []),
              ("reset_n", loc("reset_n"), "LVCMOS12", ["DRIVE 8"]),
              ("clk_p", loc("ck_t0"), "DIFF_SSTL12_DCI", []),
              ("clk_n", loc("ck_c0"), "DIFF_SSTL12_DCI", []),
              ("cke1", loc("cke1"), cmd, []), ("odt1", loc("odt1"), cmd, [])]
    for i in range(3):
        ports.append((f"cs_hi[{i}]", loc(f"cs{i + 1}_n"), cmd, []))
    data = ["OUTPUT_IMPEDANCE RDRV_40_40", "PRE_EMPHASIS RDRV_240", "EQUALIZATION EQ_LEVEL2"]
    # the board file's byte of each of the DIMM's data bytes
    byte = [8 if udimm and i == CB_BYTE[ch] else i for i in range(9)]
    for i in range(64 if udimm else 72):
        ports.append((f"dq[{i}]", loc(f"dq{8 * byte[i // 8] + i % 8}"), "POD12_DCI", data))
    if udimm:
        # byte i: the lower nibble's strobe (the DIMM's DQS_i), DM_n on the upper's _t pin (an
        # output: no equalization)
        for i in range(8):
            ports.append((f"dqs_p[{i}]", loc(f"dqs_t{2 * byte[i]}"), "DIFF_POD12_DCI", data))
            ports.append((f"dqs_n[{i}]", loc(f"dqs_c{2 * byte[i]}"), "DIFF_POD12_DCI", data))
        for i in range(8):
            ports.append((f"dm[{i}]", loc(f"dqs_t{2 * byte[i] + 1}"), "POD12_DCI", data[:2]))
    else:
        for k in range(18):
            ports.append((f"dqs_p[{k}]", loc(f"dqs_t{k}"), "DIFF_POD12_DCI", data))
            ports.append((f"dqs_n[{k}]", loc(f"dqs_c{k}"), "DIFF_POD12_DCI", data))
    # checks: in the package, in this channel's banks and SLR; each strobe with its nibble
    for port, pin, *_ in ports:
        if pin not in pk:
            problems.append(f"c{ch} {port}: pin {pin} not in the package")
            continue
        name, grp, bank, iot, slr = pk[pin]
        if int(bank) not in BANKS[ch] and not port.startswith("reset_n"):
            problems.append(f"c{ch} {port}: {pin} in bank {bank}, not {BANKS[ch]}")
        if int(slr) != SLR[ch]:
            problems.append(f"c{ch} {port}: {pin} in SLR{slr}, not SLR{SLR[ch]}")
    for k in range(18):
        s = pk[loc(f"dqs_t{k}")]
        nib = {(pk[loc(f"dq{4 * k + j}")][2], pk[loc(f"dq{4 * k + j}")][1]) for j in range(4)}
        if nib != {(s[2], s[1])} or "DBC" not in s[0] and "QBC" not in s[0]:
            problems.append(f"c{ch} dqs{k} ({loc(f'dqs_t{k}')} {s[0]} {s[2]}/{s[1]}): dq nibble {nib}")
    cb = CB_BYTE[ch]
    kind = (f" x8 UDIMM without ECC (byte i = the board file's byte i, byte {cb} its byte 8: board "
            f"byte {cb} is the DIMM's CB0..7; dqs = the board's dqs[2b], dm = its dqs_t[2b+1])"
            if udimm else "")
    lines = [HEADER.rstrip(),
             f"# DDR4 channel C{ch} (DIMM slot {ch}){',' if udimm else ':'}{kind}{':' if udimm else ''} "
             f"banks {BANKS[ch]}, SLR{SLR[ch]}.", ""]
    for port, pin, std, extra in ports:
        q = f"{{ddr4_c{ch}_{port}}}"
        lines.append(f"set_property PACKAGE_PIN {pin} [get_ports {q}]")
        lines.append(f"set_property IOSTANDARD {std} [get_ports {q}]")
        for e in extra:
            k, v = e.split()
            lines.append(f"set_property {k} {v} [get_ports {q}]")
    lines.append(f"set_property SLEW FAST [get_ports -filter {{NAME =~ ddr4_c{ch}_* && NAME !~ *reset_n}}]")
    for b in BANKS[ch]:
        lines.append(f"set_property INTERNAL_VREF 0.84 [get_iobanks {b}]")
    return "\n".join(lines) + "\n"


def board(bp, pk, problems):
    lines = [HEADER.rstrip(), "# Clocks, PCIe, LEDs, UART, I2C, the BMC's UART.", ""]
    for c in range(4):
        for pol in ("p", "n"):
            a = bp[f"default_300mhz_clk{c}_{pol}"]
            port = f"clk300_{c}_{pol}"
            lines += [f"set_property PACKAGE_PIN {a['loc']} [get_ports {port}]",
                      f"set_property IOSTANDARD {a['iostandard']} [get_ports {port}]"]
            if a.get("dqs_bias") == "TRUE":
                lines.append(f"set_property DQS_BIAS TRUE [get_ports {port}]")
        lines.append(f"create_clock -period 3.333 -name clk300_{c} [get_ports clk300_{c}_p]")
    lines += ["", "# PCIe: the reference clock (GTY quad 226) and PERST#; the x16 lanes are placed by",
              "# the XDMA IP (select_quad GTY_Quad_227, quads 224-227, SLR1)",
              f"set_property PACKAGE_PIN {bp['pcie_mgt_clkp']['loc']} [get_ports pcie_refclk_p]",
              f"set_property PACKAGE_PIN {bp['pcie_mgt_clkn']['loc']} [get_ports pcie_refclk_n]",
              "create_clock -period 10.000 -name pcie_refclk [get_ports pcie_refclk_p]",
              f"set_property PACKAGE_PIN {bp['pcie_perstn_rst']['loc']} [get_ports pcie_perst_n]",
              "set_property IOSTANDARD LVCMOS12 [get_ports pcie_perst_n]",
              "set_property PULLUP true [get_ports pcie_perst_n]",
              "set_false_path -from [get_ports pcie_perst_n]", ""]
    for i in range(3):
        a = bp[f"GPIO_LED_{i}_LS"]
        lines += [f"set_property PACKAGE_PIN {a['loc']} [get_ports {{led[{i}]}}]",
                  f"set_property IOSTANDARD LVCMOS12 [get_ports {{led[{i}]}}]",
                  f"set_property DRIVE 8 [get_ports {{led[{i}]}}]"]
    for port, name in (("uart_rx", "USB_UART_RX"), ("uart_tx", "USB_UART_TX"),
                       ("i2c_scl", "IIC_SCL_MAIN"), ("i2c_sda", "IIC_SDA_MAIN"),
                       ("i2c_mux_rst_n", "IIC_MUX_RESET_B")):
        a = bp[name]
        lines += [f"set_property PACKAGE_PIN {a['loc']} [get_ports {port}]",
                  f"set_property IOSTANDARD LVCMOS12 [get_ports {port}]"]
        # LVCMOS12's default drive (12 mA) does not exist in an HP bank (2-8 mA): place_design's
        # DRC BIVB-1 refused the I2C pins of bank 64 (2026-10-19)
        if port != "uart_rx":
            lines += [f"set_property DRIVE 8 [get_ports {port}]"]
    for name in [n for n in bp if n.startswith(("default_300", "pcie_mgt", "pcie_perst", "GPIO_LED",
                                                 "USB_UART_R", "USB_UART_T", "IIC_"))]:
        if bp[name]["loc"] not in pk:
            problems.append(f"{name}: {bp[name]['loc']} not in the package")
    # The board management controller's UART (the MSP432, U19): not in the board file. Its pins are
    # the VCU1525 master XDC's (FPGA_TXD_MSP BB19, the BMC's RX; FPGA_RXD_MSP BA19, its TX), and the
    # drive and slew are those of the helper image that first read the BMC on the card (2026-10-21).
    # The line is asynchronous: the receiver synchronizes it (otpu_bmc_uart).
    lines += ["", "# the board management controller's UART, 115200 8E1 (otpu_bmc_uart; docs/bcu1525.md",
              "# section 13): BB19 the BMC's RX, BA19 its TX (the VCU1525 master XDC)"]
    for port, loc in (("bmc_tx", "BB19"), ("bmc_rx", "BA19")):
        lines += [f"set_property PACKAGE_PIN {loc} [get_ports {port}]",
                  f"set_property IOSTANDARD LVCMOS12 [get_ports {port}]"]
        if loc not in pk:
            problems.append(f"{port}: {loc} not in the package")
    lines += ["set_property DRIVE 4 [get_ports bmc_tx]", "set_property SLEW SLOW [get_ports bmc_tx]",
              "set_false_path -to [get_ports bmc_tx]", "set_false_path -from [get_ports bmc_rx]"]
    lines += ["", "# configuration: Master SPI x4 from the MT25QU01G (1.8 V), as the VCU1525 (UG1268);",
              "# the over-temperature shutdown, as LiteX's platform (actively cooled boards still",
              "# overheat without airflow)",
              "set_property CONFIG_VOLTAGE 1.8 [current_design]",
              "set_property BITSTREAM.CONFIG.CONFIGFALLBACK ENABLE [current_design]",
              "set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]",
              "set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]",
              "set_property BITSTREAM.CONFIG.CONFIGRATE 85.0 [current_design]",
              "set_property BITSTREAM.CONFIG.EXTMASTERCCLK_EN disable [current_design]",
              "set_property BITSTREAM.CONFIG.SPI_FALL_EDGE YES [current_design]",
              "set_property BITSTREAM.CONFIG.UNUSEDPIN PULLUP [current_design]",
              "set_property BITSTREAM.CONFIG.OVERTEMPSHUTDOWN ENABLE [current_design]"]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pins", help="part0_pins.xml (default: download)")
    ap.add_argument("--pkg", help="xcvu9pfsgd2104pkg.txt (default: download)")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    bp, pk = board_pins(fetch(a.pins, PINS_URL)), package(fetch(a.pkg, PKG_URL))
    problems = []
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for ch in range(4):
        (out / f"ddr4_c{ch}.pins.xdc").write_text(ddr4(ch, bp, pk, problems))
        (out / f"ddr4_c{ch}.udimm.pins.xdc").write_text(ddr4(ch, bp, pk, problems, udimm=True))
    (out / "bcu1525_pins.xdc").write_text(board(bp, pk, problems))
    print(f"{len(bp)} board pins, {len(pk)} package pins; checks: "
          f"{'all pass' if not problems else str(len(problems)) + ' problems'}")
    for p in problems:
        print("  " + p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
