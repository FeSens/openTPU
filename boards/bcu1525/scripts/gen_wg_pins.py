#!/usr/bin/env python3
"""The BCU1525 WG build's pin constraints (constraints/bcu1525_wg_pins.xdc: the top
rtl/boards/bcu1525/otpu_fpga_top_bcu_wg.sv, four DDR4 MIGs) from the LiteDRAM build's generated
files (gen_pins.py: constraints/ddr4_c<d>.udimm.pins.xdc, constraints/bcu1525_pins.xdc).

The MIGs' pins take the same pads, renamed to the IP's signals (the top's ddr4_c<d>_<signal>):
a[13:0] -> adr[13:0], we_n / cas_n / ras_n -> adr[14] / adr[15] / adr[16], clk_p / clk_n -> ck_t /
ck_c, dqs_p / dqs_n -> dqs_t / dqs_c, dm -> dm_n; act_n, ba, bg, cke, odt, cs_n, reset_n, dq as
they are. They get their pads alone: the I/O standards, drive and termination are the IP's own
(its constraints). The pins a single-rank UDIMM's controller does not drive (par, cke1, odt1,
cs_hi) keep their names and the LiteDRAM build's settings (the top drives them idle). From
bcu1525_pins.xdc: the board clocks' pads (LVDS, DQS_BIAS) with a clock at the MIGs' input period
(3.332 ns, the IP's nearest to the 300 MHz oscillators), PCIe, the LEDs, the UART's TX, the BMC's
UART and the configuration settings; not the board's I2C or the UART's RX (the top has neither).
C0's pads under the IP: its example design on them, placed and routed clean (2026-10-27).

    python3 boards/bcu1525/scripts/gen_wg_pins.py
"""
import re
from pathlib import Path

CONS = Path(__file__).resolve().parents[1] / "constraints"
REN = {"a": "adr", "dqs_p": "dqs_t", "dqs_n": "dqs_c", "dm": "dm_n", "ba": "ba", "bg": "bg",
       "dq": "dq"}
ONE = {"we_n": "adr[14]", "cas_n": "adr[15]", "ras_n": "adr[16]", "clk_p": "ck_t", "clk_n": "ck_c",
       "act_n": "act_n", "cke": "cke", "odt": "odt", "cs_n": "cs_n", "reset_n": "reset_n"}
IDLE = ("par", "cke1", "odt1", "cs_hi")
DROP_PORTS = ("i2c_scl", "i2c_sda", "i2c_mux_rst_n", "uart_rx")


def dimm(d: int) -> list[str]:
    src = (CONS / f"ddr4_c{d}.udimm.pins.xdc").read_text()
    out = [f"# DIMM C{d}: the MIG's pads (from ddr4_c{d}.udimm.pins.xdc), then the idle pins"]
    idle = []
    for line in src.splitlines():
        m = re.match(r"set_property (\S+) (\S+) \[get_ports (?:\{([^}]+)\}|([^\s\]]+))\]\s*$", line)
        if not m:
            if "get_iobanks" in line:           # LiteDRAM's banks' VREF: the MIG trains each
                continue                        # data byte's own (its HPIO_VREFs)
            elif line.startswith("set_property") and "-filter" not in line:   # (LiteDRAM's slews)
                raise SystemExit(f"gen_wg_pins: {line}")
            continue
        prop, val = m.group(1), m.group(2)
        port = m.group(3) or m.group(4)
        pm = re.fullmatch(rf"ddr4_c{d}_(\w+?)(?:\[(\d+)\])?", port)
        if not pm:
            raise SystemExit(f"gen_wg_pins: {port} in ddr4_c{d}.udimm.pins.xdc")
        name, idx = pm.groups()
        if name in IDLE:
            idle.append(line)
            continue
        if prop != "PACKAGE_PIN":
            continue
        if idx is not None and name in REN:
            new = f"ddr4_c{d}_{REN[name]}[{idx}]"
        elif idx is None and name in ONE:
            new = f"ddr4_c{d}_{ONE[name]}"
        else:
            raise SystemExit(f"gen_wg_pins: no MIG signal for {port}")
        out.append(f"set_property PACKAGE_PIN {val} [get_ports {{{new}}}]")
    # a x8 UDIMM's: 17 address, 2 + 2 bank, act_n, the clock pair, cke, odt, cs_n, reset_n,
    # 64 DQ, 8 strobe pairs, 8 DM_n
    if len(out) - 1 != 17 + 4 + 1 + 2 + 4 + 64 + 16 + 8:
        raise SystemExit(f"gen_wg_pins: DIMM C{d}: {len(out) - 1} pads")
    return out + idle


def board() -> tuple[list[str], list[str]]:
    """The board's pins, and its clocks (bcu1525_wg_clocks.xdc, in the normal order: before the
    IPs' late constraints, XDMA's pcie4_ip_late.xdc grouping its sys_clk's)."""
    src = (CONS / "bcu1525_pins.xdc").read_text()
    out, clocks = [], []
    for line in src.splitlines():
        if line.startswith("#") or not line.strip():
            continue
        if any(re.search(rf"\b{p}\b", line) for p in DROP_PORTS):
            continue
        # the board clocks: C0's, C2's and C3's are their MIGs' (Differential: the IP creates
        # clk300_<d>_p's, a second one here overrode it, Constraints 18-1056); clk300_1 feeds C1's
        # MIG unbuffered (No_Buffer: no clock of the IP's) and the clock wizard
        m = re.match(r"create_clock -period \S+ -name (clk300_\d) \[get_ports (clk300_\d_p)\]", line)
        if m and m.group(1) != "clk300_1":
            continue
        if m:
            line = f"create_clock -period 3.332 -name {m.group(1)} [get_ports {m.group(2)}]"
        (clocks if line.startswith("create_clock") else out).append(line)
    return out, clocks


def main() -> None:
    pins, clocks = board()
    lines = ["# Generated by boards/bcu1525/scripts/gen_wg_pins.py -- do not edit.",
             "# The BCU1525 at WG 8 (otpu_fpga_top_bcu_wg): the board's pins and the four DDR4 MIGs'.",
             "# Pads: AMD XilinxBoardStore 2024.1, boards/Xilinx/vcu1525/1.3/part0_pins.xml (Copyright 2023",
             "# Advanced Micro Devices, Inc., Apache License 2.0), through gen_pins.py's files; the BCU1525",
             "# is a VCU1525 build.",
             *pins]
    for d in range(4):
        lines += ["", *dimm(d)]
    (CONS / "bcu1525_wg_pins.xdc").write_text("\n".join(lines) + "\n")
    (CONS / "bcu1525_wg_clocks.xdc").write_text("\n".join([
        "# Generated by boards/bcu1525/scripts/gen_wg_pins.py -- do not edit.",
        "# The BCU1525 at WG 8: the board clocks no IP creates (C0's, C2's and C3's are their MIGs').",
        *clocks]) + "\n")
    n = sum(1 for x in lines if "PACKAGE_PIN" in x)
    print(f"bcu1525_wg_pins.xdc: {n} pads; bcu1525_wg_clocks.xdc: {len(clocks)} clocks")


if __name__ == "__main__":
    main()
