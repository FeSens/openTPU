#!/usr/bin/env bash
# Is the committed LitePCIe core what tools/litepcie/gen_core.py makes? Regenerates it and compares
# it with boards/ypcb-00338/litepcie/ (otpu_litepcie.v, otpu_litepcie.xdc, otpu_litepcie_mem.init
# -- the identifier ROM the Verilog $readmemh's --, pcie_s7.tcl, the sha256s in core.json), its
# csr.csv with opentpu/host/litepcie/ and its csr.h with the driver's (opentpu/host/pcie/otpu).
# Exit 1 on any drift.
#
#   tools/litepcie/check_core.sh                  # PYTHON (default: $LITEPCIE_VENV/bin/python)
#   tools/litepcie/check_core.sh --setup DIR      # first make DIR a venv (uv) with migen, litex and
#                                                 # litepcie at core.json's commits, then check
#   tools/litepcie/check_core.sh --update         # regenerate and overwrite the committed core and
#                                                 # host files, rewrite core.json's hashes
#
# As tools/litedram/check_core.sh: LiteX is not part of the repository's environment. A
# regenerated core differs from the committed one only in its generation date and in the
# instance tree LiteX prints in a comment, both left out of the comparison.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
core="$root/boards/ypcb-00338/litepcie"
host="$root/opentpu/host/litepcie"
drv="$root/opentpu/host/pcie/otpu"
update=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --setup)
      venv="$2"; shift 2
      pkgs=$(python3 -c "import json,sys; p=json.load(open(sys.argv[1]))['packages']
print(' '.join(f\"git+{v['url']}@{v['commit']}\" for v in p.values()))" "$core/core.json")
      uv venv --python 3.11 "$venv"
      # shellcheck disable=SC2086
      VIRTUAL_ENV="$venv" uv pip install $pkgs
      LITEPCIE_VENV="$venv";;
    --update) update=1; shift;;
    *) echo "usage: $0 [--setup DIR] [--update]" >&2; exit 2;;
  esac
done
py="${PYTHON:-${LITEPCIE_VENV:+$LITEPCIE_VENV/bin/python}}"
if [[ -z "$py" ]]; then echo "set PYTHON or LITEPCIE_VENV (or --setup DIR)" >&2; exit 2; fi

out="$(mktemp -d "${TMPDIR:-/tmp}/otpu_pcore.XXXXXX")"
trap 'rm -rf "$out"' EXIT
args=()
while IFS= read -r a; do args+=("$a"); done < <(python3 -c "import json,sys
for a in json.load(open(sys.argv[1]))['args']: print('core' if a == '<dir>' else a)" "$core/core.json")
(cd "$out" && "$py" "$here/gen_core.py" "${args[@]}" > gen.log 2>&1) || { tail -20 "$out/gen.log"; exit 1; }
new="$out/core"

# the generated Verilog without its date and its instance-tree comment
norm_v() { awk '$0 == "/*" {skip = 1} !skip && !/Date       :/ && !/Auto-Generated by LiteX on/ {print} $0 == "*/" {skip = 0}' "$1"; }
norm_csv() { grep -v '^#' "$1"; }
files="otpu_litepcie.v otpu_litepcie.xdc otpu_litepcie_mem.init pcie_s7.tcl"

if [[ $update == 1 ]]; then
  for f in $files; do cp "$new/$f" "$core/"; done
  cp "$new/csr.csv" "$host/"
  cp "$new/csr.h" "$drv/"
  python3 - "$core/core.json" "$core" "$files" <<'EOF'
import hashlib, json, sys
from pathlib import Path
p, d, names = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3].split()
info = json.loads(p.read_text())
info["sha256"] = {n: hashlib.sha256((d / n).read_bytes()).hexdigest() for n in names}
p.write_text(json.dumps(info, indent=1) + "\n")
EOF
  echo "core updated in $core (and csr.csv in $host, csr.h in $drv); commit them together"
  echo "(a changed port list: boards/ypcb-00338/sim/otpu_litepcie_stub.sv too)"
  exit 0
fi

fail=0
(cd "$core" && python3 - <<'EOF') || fail=1
import hashlib, json
info = json.load(open("core.json"))
for name, h in info["sha256"].items():
    got = hashlib.sha256(open(name, "rb").read()).hexdigest()
    if got != h:
        print(f"{name}: sha256 {got}, core.json says {h}")
        raise SystemExit(1)
EOF
if ! diff -q <(norm_v "$core/otpu_litepcie.v") <(norm_v "$new/otpu_litepcie.v") > /dev/null; then
  echo "otpu_litepcie.v differs from gen_core.py's:"; diff <(norm_v "$core/otpu_litepcie.v") <(norm_v "$new/otpu_litepcie.v") | head -20; fail=1
fi
for f in otpu_litepcie.xdc otpu_litepcie_mem.init pcie_s7.tcl; do
  cmp -s "$core/$f" "$new/$f" || { echo "$f differs"; fail=1; }
done
diff -q <(norm_csv "$host/csr.csv") <(norm_csv "$new/csr.csv") > /dev/null || { echo "csr.csv differs"; fail=1; }
cmp -s "$drv/csr.h" "$new/csr.h" || { echo "csr.h differs"; fail=1; }
if [[ $fail == 0 ]]; then echo "LitePCIe core: matches gen_core.py"; else echo "LitePCIe core: DRIFT"; fi
exit $fail
