#!/usr/bin/env python3
"""Macro placement candidates for the nangate45-small ASIC block (27 macros), planned by hand
with OpenLayout's planner skill (skills/skills_Nangate45/1.macro_place/SKILL_planner.md) and
its macro clusters (dataflow/). Writes <out>/cand<N>/macro_place.tcl (place_macro commands).

    python3 gen_candidates.py FLOORPLAN_LOG OUT_DIR

FLOORPLAN_LOG is scripts/floorplan.tcl's log: the core box is read from its "Core :" line. The
floorplan's I/O pins are on the left, bottom and right edges (the top edge is free). Every macro
has its pins on the left edge in R0, so only R0 (pins left) and MY (pins right) are used; x is
kept on the 0.19 um site grid and y on the 1.4 um row grid from the core origin. The top row
is kept one row below the core top: place_macro moves macros up by 0.035 um to put their pins
on the metal3 tracks.
"""
import os
import re
import sys

if len(sys.argv) != 3:
    sys.exit(__doc__)
_m = re.search(r"Core : \(([\d.]+), ([\d.]+)\) - \(([\d.]+), ([\d.]+)\)", open(sys.argv[1]).read())
X0, Y0, X1, Y1 = (float(v) for v in _m.groups())
Y1 -= 1.4
SX, SY = 0.19, 1.4
SIZE = {"t": (287.66, 289.8), "imem": (327.37, 327.6), "dma": (136.42, 137.2),
        "fd": (70.3, 82.6), "fd3": (55.48, 57.4), "fs": (95.38, 96.6),
        "act": (45.41, 128.8), "asc": (29.83, 47.6)}
P = "u_slice."
S = r".u_t.g_d\[0\].g_c\[%d\].g_2p.u_m.g_%s.u_m"
NAME = {}
for ci, port in enumerate((0, 1, 4)):                 # TMEM: 3 copies x 4 banks
    for b in range(4):
        NAME[f"t{ci}{b}"] = (P + rf"u_tmem.g_port\[{port}\].g_copy.g_bank\[{b}\].g_ram.u_ram" + S % (0, "4096x32"), "t")
for c in range(2):
    NAME[f"imem{c}"] = (P + "u_seq.u_imem" + S % (c, "1024x128"), "imem")
    NAME[f"dma{c}"] = (P + "u_dma.u_lb" + S % (c, "128x128"), "dma")
    NAME[f"asc{c}"] = (P + rf"u_act.g_row\[{c}\].u_asc" + S % (0, "32x32"), "asc")
    for k in range(2):
        NAME[f"act{c}{k}"] = (P + rf"u_act.g_row\[{c}\].g_pc\[0\].u_act" + S % (k, "32x128"), "act")
for k in range(3):
    NAME[f"fd{k}"] = (P + rf"u_mxu.g_fd\[{k}\].u_fd" + S % (0, "64x72"), "fd")
NAME["fd3"] = (P + r"u_mxu.g_fd\[3\].u_fd" + S % (0, "64x40"), "fd3")
NAME["fs"] = (P + "u_mxu.u_fs" + S % (0, "128x64"), "fs")
assert len(NAME) == 27

W, H = SIZE["t"]


def snap(x, y):
    return (X0 + round((x - X0) / SX) * SX, Y0 + round((y - Y0) / SY) * SY)


class Cand:
    def __init__(self, title):
        self.title, self.p = title, {}

    def put(self, key, x, y, orient):
        """lower-left corner (x, y) of the placed macro; orient R0 (pins left) or MY (pins right)"""
        assert key not in self.p, key
        self.p[key] = (*snap(x, y), orient)

    def stack(self, keys, y_top, orient, left=None, right=None):
        """stack keys downwards from y_top, left- or right-aligned"""
        y = y_top
        for k in keys:
            w, h = SIZE[NAME[k][1]]
            y -= h
            self.put(k, left if left is not None else right - w, y, orient)
        return y

    def write(self, d):
        assert len(self.p) == 27, sorted(set(NAME) - set(self.p))
        os.makedirs(d, exist_ok=True)
        with open(f"{d}/macro_place.tcl", "w") as f:
            for line in self.title.splitlines():
                f.write(f"# {line.strip()}\n")
            f.write("# Generated by candidates/gen_candidates.py\n")
            for k in sorted(self.p):
                x, y, o = self.p[k]
                f.write(f"place_macro -macro_name {{{NAME[k][0]}}} -location {{{x:.3f} {y:.3f}}} -orient {o}\n")


# The six top-row slots: pairs back to back, three pin-to-pin channels, backs on the two edges
C = (X1 - X0 - 6 * W) / 3
SLOT = [X0, X0 + W + C, X0 + 2 * W + C, X0 + 3 * W + 2 * C, X0 + 4 * W + 2 * C, X1 - W]
ORI = ["MY", "R0", "MY", "R0", "MY", "R0"]
YA, YB, YC = Y1 - H, Y1 - 2 * H, Y1 - 3 * H
IW = SIZE["imem"][0]


def cand1():
    """Top band: TMEM in 2 rows of 6 on the pin-free top edge (one copy around each channel);
    a third partial row under the backs keeps the three channel mouths open: IMEM pin to pin
    across the middle channel, one ACT row on each IMEM's back, the MXU FIFOs facing the right
    ACT column, DMA under the top right corner. Nothing reaches the left / right I/O pin groups
    (at mid height)."""
    c = Cand(cand1.__doc__)
    for s in range(6):
        c.put(f"t{s // 2}{s % 2}", SLOT[s], YA, ORI[s])
        c.put(f"t{s // 2}{2 + s % 2}", SLOT[s], YB, ORI[s])
    c.put("imem0", SLOT[3] - C - IW, YB - SIZE["imem"][1], "MY")
    c.put("imem1", SLOT[3], YB - SIZE["imem"][1], "R0")
    c.stack(["act00", "act01", "asc0"], YB, "R0", right=SLOT[3] - C - IW)
    c.stack(["act10", "act11", "asc1"], YB, "MY", left=SLOT[3] + IW)
    c.stack(["fs", "fd0", "fd1", "fd2", "fd3"], YB, "R0", right=SLOT[4] + W)
    c.stack(["dma0", "dma1"], YB, "R0", right=X1)
    return c


def cand2():
    """Two corner blocks: TMEM as 2 columns x 3 rows in each top corner (pins into a 60 um
    channel inside each block); IMEM between the blocks on the top edge, pin to pin; under
    them one column on each block's inner back (ACT left, DMA + MXU FIFOs right), which
    leaves the pocket between the blocks a clean rectangle."""
    c = Cand(cand2.__doc__)
    ch = 60.0
    xl = [X0, X0 + W + ch]
    xr = [X1 - 2 * W - ch, X1 - W]
    blocks = {(0, 0): "t00", (0, 1): "t01", (1, 0): "t02", (1, 1): "t03",       # copy 0: left, rows A B
              (2, 0): "t20", (2, 1): "t21"}
    for (r, k), key in blocks.items():
        c.put(key, xl[k], Y1 - (r + 1) * H, "MY" if k == 0 else "R0")
    blocks = {(0, 0): "t10", (0, 1): "t11", (1, 0): "t12", (1, 1): "t13", (2, 0): "t22", (2, 1): "t23"}
    for (r, k), key in blocks.items():
        c.put(key, xr[k], Y1 - (r + 1) * H, "MY" if k == 0 else "R0")
    lb, rb = xl[1] + W, xr[0]                      # the blocks' inner backs
    yi = Y1 - SIZE["imem"][1]
    c.put("imem0", lb, yi, "MY")
    c.put("imem1", rb - IW, yi, "R0")
    c.stack(["act00", "act01", "act10", "act11", "asc0", "asc1"], yi, "MY", left=lb)
    c.stack(["dma0", "dma1", "fs", "fd0", "fd1", "fd2", "fd3"], yi, "R0", right=rb)
    return c


def cand3():
    """Three corners: one TMEM copy (2 x 2, pins into a 60 um channel) in the top left, the top
    right and the bottom right corner (the bottom right corner has no I/O pins); IMEM between
    the top blocks, pin to pin; DMA and the MXU FIFOs in columns on the top blocks' inner
    backs, ACT in a column on the bottom right block's back."""
    c = Cand(cand3.__doc__)
    ch = 60.0
    xl = [X0, X0 + W + ch]
    xr = [X1 - 2 * W - ch, X1 - W]
    for r in range(2):
        for k in range(2):
            o = "MY" if k == 0 else "R0"
            c.put(f"t0{2 * r + k}", xl[k], Y1 - (r + 1) * H, o)
            c.put(f"t1{2 * r + k}", xr[k], Y1 - (r + 1) * H, o)
            c.put(f"t2{2 * r + k}", xr[k], Y0 + (1 - r) * H, o)
    lb, rb = xl[1] + W, xr[0]
    yi = Y1 - SIZE["imem"][1]
    c.put("imem0", lb, yi, "MY")
    c.put("imem1", rb - IW, yi, "R0")
    c.stack(["dma0", "dma1"], yi, "MY", left=lb)
    c.stack(["fs", "fd0", "fd1", "fd2", "fd3"], yi, "R0", right=rb)
    n = ["asc1", "asc0", "act11", "act10", "act01", "act00"]
    c.stack(n[::-1], Y0 + sum(SIZE[NAME[k][1]][1] for k in n), "R0", right=rb)
    return c


if __name__ == "__main__":
    for n, f in enumerate((cand1, cand2, cand3), 1):
        f().write(f"{sys.argv[2]}/cand{n}")
        print(f"cand{n}: {f.__doc__.splitlines()[0]}")
